create or replace function public.prevent_overbooking()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_capacity integer;
  v_occupied integer;
begin
  if new.status in ('payment_reported','confirmed')
     and old.status not in ('payment_reported','confirmed') then
    select capacity into v_capacity
    from public.workshops
    where id = new.workshop_id
    for update;

    select count(*)::integer into v_occupied
    from public.registrations
    where workshop_id = new.workshop_id
      and status in ('payment_reported','confirmed')
      and id <> new.id;

    if v_occupied >= v_capacity then
      raise exception 'Oficina sem vagas disponíveis';
    end if;
  end if;

  if new.status = 'confirmed' and old.status is distinct from 'confirmed' then
    new.confirmed_at := coalesce(new.confirmed_at, now());
    new.confirmed_by := coalesce(new.confirmed_by, auth.uid());
  end if;

  if new.status = 'payment_reported' and old.status is distinct from 'payment_reported' then
    new.payment_reported_at := coalesce(new.payment_reported_at, now());
  end if;

  if new.status = 'cancelled' and old.status is distinct from 'cancelled' then
    new.cancelled_at := coalesce(new.cancelled_at, now());
  end if;

  new.updated_at := now();
  return new;
end;
$$;

