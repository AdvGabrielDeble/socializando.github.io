create or replace function public.is_workshop_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $admin$
  select
    exists (
      select 1
      from public.admin_users a
      where a.user_id = auth.uid()
    )
    or exists (
      select 1
      from public.admin_emails e
      where e.active = true
        and e.email = lower(auth.jwt()->>'email')
    );
$admin$;

create or replace function public.audit_workshop_admin_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $audit_workshop$
declare
  v_action text;
  v_id uuid;
begin
  if auth.uid() is null or not public.is_workshop_admin() then
    if tg_op = 'DELETE' then return old; else return new; end if;
  end if;

  v_action := case tg_op
    when 'INSERT' then 'workshop_created'
    when 'UPDATE' then 'workshop_updated'
    when 'DELETE' then 'workshop_deleted'
    else lower(tg_op)
  end;

  v_id := case when tg_op = 'DELETE' then old.id else new.id end;

  insert into public.admin_audit_log (
    actor_user_id, actor_email, entity_type, entity_id, action, details
  ) values (
    auth.uid(),
    lower(coalesce(auth.jwt()->>'email','')),
    'workshop',
    v_id,
    v_action,
    case
      when tg_op = 'INSERT' then jsonb_build_object(
        'title', new.title, 'date', new.event_date, 'time', new.start_time,
        'capacity', new.capacity, 'price_cents', new.price_cents, 'status', new.status
      )
      when tg_op = 'UPDATE' then jsonb_build_object(
        'before', jsonb_build_object(
          'title', old.title, 'date', old.event_date, 'start_time', old.start_time,
          'end_time', old.end_time, 'capacity', old.capacity,
          'price_cents', old.price_cents, 'status', old.status
        ),
        'after', jsonb_build_object(
          'title', new.title, 'date', new.event_date, 'start_time', new.start_time,
          'end_time', new.end_time, 'capacity', new.capacity,
          'price_cents', new.price_cents, 'status', new.status
        )
      )
      else jsonb_build_object('title', old.title, 'status', old.status)
    end
  );

  if tg_op = 'DELETE' then return old; else return new; end if;
end;
$audit_workshop$;

create or replace function public.audit_registration_admin_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $audit_registration$
begin
  if auth.uid() is null or not public.is_workshop_admin() then
    return new;
  end if;

  if old.status is distinct from new.status then
    insert into public.admin_audit_log (
      actor_user_id, actor_email, entity_type, entity_id, action, details
    ) values (
      auth.uid(),
      lower(coalesce(auth.jwt()->>'email','')),
      'registration',
      new.id,
      'registration_status_changed',
      jsonb_build_object(
        'workshop_id', new.workshop_id,
        'payment_reference', new.payment_reference,
        'from', old.status,
        'to', new.status
      )
    );
  end if;

  return new;
end;
$audit_registration$;

